const dict: Record<Key, string> = (navigator.language || 'en').toLowerCase().startsWith('de') ? de : en;

/** Translate a key; each %s is replaced by the next argument. */
/** True if a translation exists (used for option labels of unknown keys). */
export const has = (key: string): key is Key => key in dict;

export const t = (key: Key, ...args: (string | number)[]): string => {
  let i = 0;
  return dict[key].replace(/%s/g, () => String(args[i++] ?? ''));
};

/** Human-readable, translated error message for a failed request. */
export const errorText = (error: any): string => {
  const code = error?.response?.status === 429 ? '429' : errorCode(error);
  const key = `err.${code}` as Key;
  return code && key in dict ? dict[key] : httpErrorToHuman(error);
};
